#!/usr/bin/env node
// The docs page is named sections of the repo's own READMEs, rendered at build time: one source,
// so the page and the READMEs cannot drift. Writes src/app/generated/docs.ts (gitignored), which
// pages/docs.ts reads, plus the package VERSION the privacy page quotes. Run by npm start, build
// and test.
//
// Links: absolute ones stay. A relative link points into the repo: it becomes an anchor on this
// page when the target is one of the sections below, and the file on GitHub otherwise.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { Marked } from 'marked';

const repo = new URL('../../', import.meta.url);
const read = p => readFileSync(new URL(p, repo), 'utf8');

// In page order. `heading` is the README's own `##` heading, verbatim; `whole` takes a file
// without its `#` title.
export const SECTIONS = [
    { id: 'install', title: 'Install', file: 'packages/verify/README.md', heading: 'Install' },
    { id: 'cli', title: 'CLI', file: 'packages/verify/README.md', heading: 'CLI' },
    { id: 'digest', title: 'Digest', file: 'packages/verify/README.md', heading: 'Digest (for the `seo-read` skill)' },
    { id: 'seo-read', title: 'The seo-read skill', file: 'plugins/siteread/README.md', whole: true },
    { id: 'share', title: 'Share', file: 'packages/verify/README.md', heading: 'Share (opt-in)' },
    { id: 'library', title: 'Library', file: 'packages/verify/README.md', heading: 'Library' },
    { id: 'vendor-lists', title: 'Vendor lists', file: 'packages/verify/README.md', heading: 'Vendor lists' },
    { id: 'feed', title: 'The feed', file: 'packages/verify/README.md', heading: 'The feed' },
    { id: 'why', title: 'Why', file: 'packages/verify/README.md', heading: 'Why' },
];

// Relative link targets, resolved against the repo root, that this page holds. Anchors carry the
// page path: the site's <base href="/"> would send a bare "#id" to the home page.
const LINKS = { 'plugins/siteread/README.md': 'docs#seo-read' };
const REPO = 'https://github.com/synacl-iot/siteread/blob/main/';

/** The body under `## heading` up to the next `##`, skipping fenced code. Throws when missing. */
export function section(markdown, heading) {
    const lines = markdown.split('\n');
    const out = [];
    let inside = false, fence = false;
    for (const line of lines) {
        if (/^(```|~~~)/.test(line)) fence = !fence;
        if (!fence && /^## /.test(line)) {
            if (inside) break;
            inside = line.slice(3).trim() === heading;
            continue;
        }
        if (inside) out.push(line);
    }
    if (!inside && !out.length) throw new Error(`docs: no "## ${heading}" section`);
    return out.join('\n').trim();
}

/** A whole README minus its `#` title, its `##` headings one level down. */
export function whole(markdown) {
    let fence = false;
    return markdown.split('\n').filter(l => !/^# /.test(l)).map(l => {
        if (/^(```|~~~)/.test(l)) fence = !fence;
        return !fence && /^#{2,5} /.test(l) ? `#${l}` : l;
    }).join('\n').trim();
}

const slug = s => s.toLowerCase().replace(/`/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export function render(md, prefix, file = 'README.md') {
    const marked = new Marked({
        gfm: true,
        renderer: {
            heading({ tokens, depth, text }) {
                return `<h${depth} id="${prefix}-${slug(text)}">${this.parser.parseInline(tokens)}</h${depth}>\n`;
            },
            link({ href, title, tokens }) {
                const label = this.parser.parseInline(tokens);
                let target;
                if (/^(https?:|mailto:)/.test(href)) target = href;
                else if (href.startsWith('#')) target = `docs${href}`;
                else {
                    const abs = new URL(href, REPO + file).href;
                    target = abs.startsWith(REPO) ? (LINKS[abs.slice(REPO.length)] ?? abs) : null;
                }
                if (!target) return label;
                const t = title ? ` title="${title}"` : '';
                return `<a href="${target}"${t}>${label}</a>`;
            },
        },
    });
    // Wide tables scroll inside their own box on a phone instead of widening the page.
    return marked.parse(md).replace(/<table>/g, '<div class="table-scroll"><table>').replace(/<\/table>/g, '</table></div>');
}

export function build() {
    const docs = SECTIONS.map(s => {
        const md = read(s.file);
        return { id: s.id, title: s.title, html: render(s.whole ? whole(md) : section(md, s.heading), s.id, s.file) };
    });
    const { version } = JSON.parse(read('packages/verify/package.json'));
    return `// Generated by scripts/docs.mjs from the repo's READMEs. Do not edit; run \`npm run docs\`.\n\n`
        + `export const VERSION = ${JSON.stringify(version)};\n\n`
        + `export const DOCS: readonly { id: string; title: string; html: string }[] = ${JSON.stringify(docs, null, 2)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const out = new URL('../src/app/generated/', import.meta.url);
    mkdirSync(out, { recursive: true });
    writeFileSync(new URL('docs.ts', out), build());
    process.stderr.write(`docs: ${SECTIONS.length} sections → src/app/generated/docs.ts\n`);
}
